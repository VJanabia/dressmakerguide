#!/usr/bin/env node
/**
 * Outbound link check. The build audit only proves internal links resolve; this walks every
 * external link in the built site and confirms it still answers. Network dependent, so it is a
 * separate command rather than part of `npm run audit`.
 *
 *   node scripts/check-external-links.mjs
 *
 * Exit code 1 only for links that are genuinely gone (404/410). A 403, 429 or a connection
 * timeout is reported as BLOCKED, because that is what Cloudflare, anti-bot rules and this
 * machine's network produce for sites that are demonstrably alive - SteamDB, Screenhub and
 * Discord all answer a real browser while refusing a scripted request. Treat BLOCKED as
 * "check by hand", not as a broken link.
 */
import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const UA = { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126 Safari/537.36' };

async function htmlFiles(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...await htmlFiles(full));
    else if (e.name.endsWith('.html')) out.push(full);
  }
  return out;
}

const links = new Map(); // url -> Set(pages)
for (const file of await htmlFiles(dist)) {
  const html = await readFile(file, 'utf8');
  const page = '/' + path.relative(dist, file).replace(/\\/g, '/').replace(/index\.html$/, '');
  for (const m of html.matchAll(/<a\b[^>]*href="(https?:\/\/[^"]+)"/g)) {
    const url = m[1].replace(/&amp;/g, '&');
    if (url.includes('dressmakerguide.com')) continue;
    if (!links.has(url)) links.set(url, new Set());
    links.get(url).add(page);
  }
}

console.log(links.size + ' unique external links across the site');

async function probe(url) {
  let last = 'unknown';
  for (const method of ['HEAD', 'GET']) {
    try {
      const res = await fetch(url, { method, headers: UA, redirect: 'follow', signal: AbortSignal.timeout(25000) });
      if (res.status < 400) return { state: 'ok', status: res.status };
      last = res.status;
      if (method === 'GET') return { state: res.status === 404 || res.status === 410 ? 'dead' : 'blocked', status: res.status };
    } catch (e) {
      last = e.cause?.code || e.name;
    }
  }
  return { state: 'blocked', status: last };
}

const dead = [];
const blocked = [];
const results = [];
for (const [url, pages] of [...links].sort()) {
  const r = await probe(url);
  results.push({ url, ...r });
  if (r.state === 'dead') dead.push({ url, ...r, pages: [...pages].join(', ') });
  if (r.state === 'blocked') blocked.push({ url, ...r, pages: [...pages].join(', ') });
  const label = r.state === 'ok' ? '  ok     ' : r.state === 'dead' ? '  DEAD   ' : '  BLOCKED';
  console.log(label + ' ' + String(r.status).padEnd(26) + url.slice(0, 88));
}

// markdown report next to the audit
const lines = [
  '# External link check',
  '',
  'Generated by ' + String.fromCharCode(96) + 'npm run check:links' + String.fromCharCode(96) + '. ' +
    results.length + ' unique external links.',
  '',
  '| Status | Code | URL |',
  '| --- | --- | --- |',
  ...results.map((r) => '| ' + r.state + ' | ' + r.status + ' | ' + r.url + ' |'),
  '',
  dead.length ? '## Dead links (fix these)' : '## Dead links',
  '',
  dead.length ? dead.map((d) => '- ' + d.url + ' - used on ' + d.pages).join('\n') : 'None.',
  '',
  '## Blocked (verify by hand in a browser)',
  '',
  blocked.length
    ? blocked.map((b) => '- ' + b.url + ' (' + b.status + ') - used on ' + b.pages).join('\n')
    : 'None.',
  '',
  'Blocked means the server refused a scripted request with 403/429 or dropped the connection. Anti-bot',
  'protection and regional routing produce this for sites that load fine in a browser, so each one needs a',
  'human glance rather than a code change.',
  '',
].join('\n');
await (await import('node:fs/promises')).writeFile(path.join(root, 'docs', 'link-check.md'), lines, 'utf8');

console.log('');
console.log('ok: ' + (results.length - dead.length - blocked.length) + ' | dead: ' + dead.length + ' | blocked: ' + blocked.length);
if (dead.length) {
  console.log('Dead links:');
  for (const d of dead) console.log('  ! ' + d.status + '  ' + d.url + '  (used on ' + d.pages + ')');
}
console.log('Report written to docs/link-check.md');
process.exitCode = dead.length ? 1 : 0;
